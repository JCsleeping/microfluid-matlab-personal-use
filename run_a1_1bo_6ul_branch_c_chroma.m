function results = run_a1_1bo_6ul_branch_c_chroma(varargin)
% RUN_A1_1BO_6UL_BRANCH_C_CHROMA  Exact-gated Branch C chroma batch preset.
%
%   This preset uses the 2026-06-01 Python exact endpoint audit:
%     score_mode_primary = chroma
%     endpoint_default = A_full_consistency_primary
%     endpoint_sensitivity = B_residual_separation_primary
%     endpoint_status = masked_audit_passed_exact
%
%   It runs the MATLAB pipeline twice, once for endpoint A and once for
%   endpoint B. Use the A output as the default Branch C result and the B
%   output as the endpoint-sensitivity check.
%
%   Optional name-value arguments:
%       'endpoints'   - 'both' (default), 'A', or 'B'
%       'output_base' - existing/new output base directory

    opts = parse_options(varargin{:});
    repo_root = fileparts(mfilename('fullpath'));
    roi_mask = fullfile(repo_root, 'outputs', 'roi_templates_20260601', ...
        'A1_1BO_6UL', 'Mask.tif');
    crop_rect = [1, 595, 2391, 828];
    native_pixel_size_m = 10000e-6 / crop_rect(3);

    water_A = 'G:\Microfluid\00 A1 1-BO 6 UL WATER DISPLACEMENT\00 NAPL\00 NAPL 3 SECONDS_1.tif';
    napl_A = 'G:\Microfluid\00 A1 1-BO 6 UL WATER DISPLACEMENT\01 WATER\01 WATER 1 SECONDS_3.tif';
    water_B = 'G:\Microfluid\00 A1 1-BO 6 UL WATER DISPLACEMENT\00 NAPL\01 NAPL 1 SECONDS.tif';
    napl_B = 'G:\Microfluid\00 A1 1-BO 6 UL WATER DISPLACEMENT\01 WATER\00 WATER 3 SECONDS_2.tif';

    frame_paths = branch_c_frame_paths();
    frame_pages = first_page_indices(frame_paths);
    if isempty(opts.output_base)
        timestamp = datestr(now, 'yyyymmdd_HHMMSS');
        base_output = fullfile(repo_root, 'outputs', ...
            ['matlab_branch_c_a1_1bo_6ul_chroma_' timestamp]);
    else
        base_output = opts.output_base;
    end

    common_overrides = { ...
        'data_path', 'G:\Microfluid\00 A1 1-BO 6 UL WATER DISPLACEMENT\01 WATER', ...
        'multipage_tif_path', frame_paths, ...
        'pages', frame_pages, ...
        'physical.pixel_size', native_pixel_size_m, ...
        'calibration.native_pixel_size_m', native_pixel_size_m, ...
        'preprocess.rotation_angle', 0, ...
        'preprocess.manual_crop_rect', crop_rect, ...
        'illumination.method', 'morphological', ...
        'illumination.kernel_size', 50, ...
        'flow_domain.extraction_method', 'mask', ...
        'flow_domain.flow_domain_mask_path', roi_mask, ...
        'flow_domain.mask_grid', 'native_full', ...
        'flow_domain.mask_resize_method', 'nearest', ...
        'flow_domain.expected_porosity', NaN, ...
        'flow_domain.hard_fail', false, ...
        'qc.flow_domain.hard_fail', false, ...
        'water_reference_image_page', 1, ...
        'water_reference_crop_rect', crop_rect, ...
        'napl_reference_image_page', 1, ...
        'napl_reference_crop_rect', crop_rect, ...
        'segmentation.method', 'dual_reference_fraction_hysteresis', ...
        'bulk_sn.enabled', true, ...
        'bulk_sn.primary_output', true, ...
        'bulk_sn.score_mode', 'chroma', ...
        'bulk_sn.statistic', 'winsorized_mean', ...
        'bulk_sn.winsor_percentiles', [1 99], ...
        'bulk_sn.mask_id', 'flow_domain', ...
        'bulk_sn.endpoint_status', 'masked_audit_passed_exact', ...
        'bulk_sn.rgb_source', 'corrected_quantitative', ...
        'bulk_sn.min_endpoint_delta', 1.0, ...
        'visualization.show_figures', false, ...
        'visualization.save_figures', true, ...
        'output.checkpoint', true, ...
        'output.emit_manifest', true, ...
        'manifest.hash_policy', 'size_mtime_only'};

    config_A = config_pipeline(common_overrides{:}, ...
        'water_reference_image', water_A, ...
        'napl_reference_image', napl_A, ...
        'bulk_sn.endpoint_source', 'A_full_consistency_primary', ...
        'output_path', fullfile(base_output, 'endpoint_A_full_consistency_primary'));

    config_B = config_pipeline(common_overrides{:}, ...
        'water_reference_image', water_B, ...
        'napl_reference_image', napl_B, ...
        'bulk_sn.endpoint_source', 'B_residual_separation_primary', ...
        'output_path', fullfile(base_output, 'endpoint_B_residual_separation_primary'));

    results = struct();
    if opts.run_A
        results.endpoint_A = main_DNAPL_pipeline(config_A);
    end
    if opts.run_B
        results.endpoint_B = main_DNAPL_pipeline(config_B);
    end
    results.output_base = base_output;
    results.frame_page_indices = frame_pages;
end


function opts = parse_options(varargin)
    opts = struct('run_A', true, 'run_B', true, 'output_base', '');
    if mod(numel(varargin), 2) ~= 0
        error('run_a1_1bo_6ul_branch_c_chroma:badOptions', ...
            'Options must be name-value pairs.');
    end
    for idx = 1:2:numel(varargin)
        name = lower(char(string(varargin{idx})));
        value = varargin{idx + 1};
        switch name
            case 'endpoints'
                endpoint_value = lower(char(string(value)));
                switch endpoint_value
                    case 'both'
                        opts.run_A = true;
                        opts.run_B = true;
                    case 'a'
                        opts.run_A = true;
                        opts.run_B = false;
                    case 'b'
                        opts.run_A = false;
                        opts.run_B = true;
                    otherwise
                        error('run_a1_1bo_6ul_branch_c_chroma:badEndpointOption', ...
                            'endpoints must be "both", "A", or "B".');
                end
            case 'output_base'
                opts.output_base = char(string(value));
            otherwise
                error('run_a1_1bo_6ul_branch_c_chroma:unknownOption', ...
                    'Unknown option: %s', name);
        end
    end
end


function paths = branch_c_frame_paths()
    full_napl = { ...
        'G:\Microfluid\00 A1 1-BO 6 UL WATER DISPLACEMENT\01 WATER\00 WATER 3 SECONDS.tif', ...
        'G:\Microfluid\00 A1 1-BO 6 UL WATER DISPLACEMENT\01 WATER\00 WATER 3 SECONDS_1.tif', ...
        'G:\Microfluid\00 A1 1-BO 6 UL WATER DISPLACEMENT\01 WATER\00 WATER 3 SECONDS_2.tif', ...
        'G:\Microfluid\00 A1 1-BO 6 UL WATER DISPLACEMENT\01 WATER\01 WATER 1 SECONDS.tif', ...
        'G:\Microfluid\00 A1 1-BO 6 UL WATER DISPLACEMENT\01 WATER\01 WATER 1 SECONDS_1.tif', ...
        'G:\Microfluid\00 A1 1-BO 6 UL WATER DISPLACEMENT\01 WATER\01 WATER 1 SECONDS_2.tif', ...
        'G:\Microfluid\00 A1 1-BO 6 UL WATER DISPLACEMENT\01 WATER\01 WATER 1 SECONDS_3.tif'};
    residual = cell(1, 43);
    residual{1} = 'G:\Microfluid\00 A1 1-BO 6 UL WATER DISPLACEMENT\01 WATER\02 WATER 3 SECONDS.tif';
    for idx = 1:42
        residual{idx + 1} = sprintf(['G:\\Microfluid\\00 A1 1-BO 6 UL WATER DISPLACEMENT\\01 WATER\\' ...
            '02 WATER 3 SECONDS_%d.tif'], idx);
    end
    paths = [full_napl, residual];
end


function pages = first_page_indices(paths)
    pages = zeros(1, numel(paths));
    next_page = 1;
    for idx = 1:numel(paths)
        pages(idx) = next_page;
        info = imfinfo(paths{idx});
        next_page = next_page + numel(info);
    end
end
