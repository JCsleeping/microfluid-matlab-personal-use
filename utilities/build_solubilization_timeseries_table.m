function T = build_solubilization_timeseries_table(time_vector, sol)
% BUILD_SOLUBILIZATION_TIMESERIES_TABLE Build canonical solubilization table.

    if nargin < 2 || ~isstruct(sol)
        error('build_solubilization_timeseries_table:invalidInput', ...
            'time_vector and sol struct are required.');
    end

    time_vector = reshape(time_vector, [], 1);
    num_rows = numel(time_vector);

    primary_sn = get_required_series(sol, 'saturation_vs_time', num_rows);

    cols = { ...
        time_vector, ...
        primary_sn, ...
        get_optional_series(sol, 'S_NAPL_color_raw_vs_time', num_rows), ...
        get_optional_series(sol, 'S_NAPL_color_vs_time', num_rows), ...
        get_optional_series(sol, 'Sn_mask_secondary_vs_time', num_rows), ...
        get_optional_series(sol, 'mask_color_abs_difference_vs_time', num_rows), ...
        get_required_or_default_string_series(sol, ...
            'bulk_sn_score_mode_vs_time', num_rows, ""), ...
        get_required_or_default_string_series(sol, ...
            'bulk_sn_endpoint_status_vs_time', num_rows, "not_computed"), ...
        get_required_or_default_string_series(sol, ...
            'bulk_sn_endpoint_source_vs_time', num_rows, ""), ...
        get_required_or_default_string_series(sol, ...
            'bulk_sn_mask_id_vs_time', num_rows, ""), ...
        get_required_or_default_string_series(sol, ...
            'bulk_sn_rgb_source_vs_time', num_rows, ""), ...
        get_optional_series(sol, 'bulk_sn_score_frame_vs_time', num_rows), ...
        get_optional_series(sol, 'bulk_sn_score_water_ref_vs_time', num_rows), ...
        get_optional_series(sol, 'bulk_sn_score_napl_ref_vs_time', num_rows), ...
        get_optional_series(sol, 'bulk_sn_core_flow_area_px_vs_time', num_rows), ...
        get_optional_series(sol, 'bulk_sn_flow_domain_area_px_vs_time', num_rows), ...
        get_optional_series(sol, 'bulk_sn_edge_excluded_fraction_vs_time', num_rows), ...
        get_required_or_default_string_series(sol, ...
            'bulk_sn_qc_status_vs_time', num_rows, ""), ...
        get_optional_or_default_series(sol, 'Sn_lower_vs_time', num_rows, ...
            primary_sn), ...
        get_optional_or_default_series(sol, 'Sn_mid_vs_time', num_rows, ...
            primary_sn), ...
        get_optional_or_default_series(sol, 'Sn_upper_vs_time', num_rows, ...
            primary_sn), ...
        get_required_or_default_series(sol, 'Sn_uncertainty_width_vs_time', num_rows, 0), ...
        get_required_or_default_series(sol, 'uncertain_area_fraction_vs_time', num_rows, 0), ...
        get_required_series(sol, 'num_blobs_vs_time', num_rows), ...
        get_required_series(sol, 'mean_blob_size_vs_time', num_rows), ...
        get_required_series(sol, 'interface_area_vs_time', num_rows), ...
        get_optional_series(sol, 'max_blob_frac_vs_time', num_rows), ...
        get_optional_series(sol, 'Req_median_vs_time', num_rows), ...
        get_optional_series(sol, 'Req_mean_vs_time', num_rows), ...
        get_optional_series(sol, 'Req_std_vs_time', num_rows), ...
        get_optional_series(sol, 'mean_circularity_vs_time', num_rows), ...
        get_optional_series(sol, 'a_i_2D_vs_time', num_rows), ...
        get_optional_series(sol, 'n_droplets_vs_time', num_rows), ...
        get_optional_series(sol, 'n_columns_vs_time', num_rows), ...
        get_optional_series(sol, 'n_clusters_vs_time', num_rows), ...
        get_optional_series(sol, 'frac_droplets_vs_time', num_rows), ...
        get_optional_series(sol, 'frac_columns_vs_time', num_rows), ...
        get_optional_series(sol, 'frac_clusters_vs_time', num_rows), ...
        get_required_or_default_series(sol, 'processing_scale_factor', num_rows, 1), ...
        get_required_or_default_string_series(sol, 'primary_branch', num_rows, "native"), ...
        get_required_or_default_string_series(sol, 'sn_semantics_version', num_rows, "v3.3_processing_grid_sf1"), ...
        get_required_or_default_string_series(sol, 'frame_validation_status', num_rows, "not_run"), ...
        get_required_or_default_string_series(sol, 'object_validation_status', num_rows, "not_object_matched"), ...
        get_required_or_default_string_series(sol, 'quantification_status', num_rows, "eligible_interpolation_assisted"), ...
        get_optional_series(sol, 'invalid_endpoint_fraction_vs_time', num_rows), ...
        get_required_or_default_series(sol, 'global_endpoint_fallback_active_vs_time', num_rows, false), ...
        get_required_or_default_series(sol, 'endpoint_per_pixel_unreliable_vs_time', num_rows, false), ...
        get_optional_series(sol, 'hsv_candidate_gated_fraction_vs_time', num_rows), ...
        get_optional_series(sol, 'frac_p50_vs_time', num_rows), ...
        get_optional_series(sol, 'frac_raw_p50_vs_time', num_rows), ...
        get_optional_series(sol, 'mask_bulk_abs_difference_vs_time', num_rows), ...
        get_required_or_default_string_series(sol, 'segmentation_qc_status_vs_time', num_rows, ""), ...
        get_required_or_default_string_series(sol, 'endpoint_mode_used_vs_time', num_rows, "")};

    names = {'Time', 'Sn', 'S_NAPL_color_raw', 'S_NAPL_color', ...
        'Sn_mask_secondary', 'mask_color_abs_difference', 'score_mode', ...
        'endpoint_status', 'endpoint_source', 'mask_id', 'rgb_source', ...
        'score_frame', 'score_water_ref', 'score_napl_ref', ...
        'core_flow_area_px', 'flow_domain_area_px', ...
        'edge_excluded_fraction', 'bulk_sn_qc_status', ...
        'Sn_lower', 'Sn_mid', 'Sn_upper', ...
        'Sn_uncertainty_width', 'uncertain_area_fraction', ...
        'NumBlobs', 'MeanBlobSize', 'InterfaceArea', ...
        'MaxBlobFrac', 'ReqMedian', 'ReqMean', 'ReqStd', ...
        'MeanCircularity', 'a_i_2D', 'nDroplets', 'nColumns', ...
        'nClusters', 'fracDroplets', 'fracColumns', 'fracClusters', ...
        'processing_scale_factor', 'primary_branch', 'sn_semantics_version', ...
        'frame_validation_status', 'object_validation_status', 'quantification_status', ...
        'invalid_endpoint_fraction', 'global_endpoint_fallback_active', ...
        'endpoint_per_pixel_unreliable', 'hsv_candidate_gated_fraction', ...
        'frac_p50', 'frac_raw_p50', 'mask_bulk_abs_difference', ...
        'segmentation_qc_status', 'endpoint_mode_used'};

    if isfield(sol, 'mass_dissolved_vs_time') && ~isempty(sol.mass_dissolved_vs_time)
        cols{end+1} = validate_series(sol.mass_dissolved_vs_time, num_rows, ...
            'sol.mass_dissolved_vs_time');
        names{end+1} = 'MassDissolvedKg';
    end

    T = table(cols{:}, 'VariableNames', names);
    T = append_region_columns(T, sol, num_rows);
    T.Sn_processing = T.Sn;
    T.InterfaceArea_processing_px = T.InterfaceArea;
    T.InterfaceLength_processing_px = T.InterfaceArea_processing_px;
    T.InterfaceLength_native_equiv_px = T.InterfaceLength_processing_px ./ ...
        T.processing_scale_factor;
end


function values = get_required_series(sol, field_name, expected_length)
    if ~isfield(sol, field_name) || isempty(sol.(field_name))
        error('build_solubilization_timeseries_table:missingRequiredSeries', ...
            'Required solubilization field %s is missing or empty.', ...
            ['sol.' field_name]);
    end

    values = validate_series(sol.(field_name), expected_length, ['sol.' field_name]);
end


function T = append_region_columns(T, sol, expected_length)
    if ~isfield(sol, 'bulk_sn_regions_vs_time') || ...
            isempty(sol.bulk_sn_regions_vs_time)
        return;
    end

    values = sol.bulk_sn_regions_vs_time;
    if size(values, 1) ~= expected_length
        error('build_solubilization_timeseries_table:lengthMismatch', ...
            'sol.bulk_sn_regions_vs_time must contain %d rows; got %d.', ...
            expected_length, size(values, 1));
    end

    for idx = 1:size(values, 2)
        T.(sprintf('S_NAPL_color_bin_%02d', idx)) = values(:, idx);
    end
end


function values = get_optional_series(sol, field_name, expected_length)
    if ~isfield(sol, field_name) || isempty(sol.(field_name))
        values = nan(expected_length, 1);
        return;
    end

    values = validate_series(sol.(field_name), expected_length, ['sol.' field_name]);
end


function values = get_required_or_default_series(sol, field_name, expected_length, default_value)
    if ~isfield(sol, field_name) || isempty(sol.(field_name))
        values = repmat(default_value, expected_length, 1);
        return;
    end
    values = validate_series(sol.(field_name), expected_length, ['sol.' field_name]);
end


function values = get_optional_or_default_series(sol, field_name, expected_length, default_values)
    if ~isfield(sol, field_name) || isempty(sol.(field_name))
        values = reshape(default_values, [], 1);
    else
        values = validate_series(sol.(field_name), expected_length, ['sol.' field_name]);
    end
    if numel(values) ~= expected_length
        error('build_solubilization_timeseries_table:lengthMismatch', ...
            '%s fallback must contain %d elements; got %d.', ...
            field_name, expected_length, numel(values));
    end
end


function values = get_required_or_default_string_series(sol, field_name, expected_length, default_value)
    if ~isfield(sol, field_name) || isempty(sol.(field_name))
        values = repmat(string(default_value), expected_length, 1);
        return;
    end
    values = reshape(string(sol.(field_name)), [], 1);
    if numel(values) ~= expected_length
        error('build_solubilization_timeseries_table:lengthMismatch', ...
            'sol.%s must contain %d elements; got %d.', ...
            field_name, expected_length, numel(values));
    end
end


function values = validate_series(values, expected_length, label)
    values = reshape(values, [], 1);
    if numel(values) ~= expected_length
        error('build_solubilization_timeseries_table:lengthMismatch', ...
            '%s must contain %d elements; got %d.', ...
            label, expected_length, numel(values));
    end
end
